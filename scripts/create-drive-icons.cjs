// Regenerates checked-in ICO badges from the app's code-native service colours/letters.
// Run with PLAYWRIGHT_MODULE pointing to an installed Playwright package.
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async () => {
 const text = fs.readFileSync('src/api.ts','utf8');
 const services = [...text.matchAll(/\{ id: '([^']+)', name: '[^']+', description: '[^']+', color: '(#[a-f0-9]+)', letters: '([^']+)'/g)];
 if (services.length !== 30) throw Error('Update the icon generator for the service catalogue');
 const browser = await chromium.launch({headless:true,channel:'msedge'});
 const page = await browser.newPage();
 fs.mkdirSync('src-tauri/icons/drives',{recursive:true});
 const arms = [];
 for (const [,id,color,letters] of services) {
  const artwork = id === 'drive' ? '<path fill="#25a65a" d="M8 2h8L5 21 1 14z"/><path fill="#f6c344" d="M8 2h8l8 14h-8z"/><path fill="#4285f4" d="M5 21l4-7h15l-4 7z"/>' : id === 'dropbox' ? '<path fill="white" d="m6 4 6 4-6 4-6-4 6-4m12 0 6 4-6 4-6-4 6-4M6 12l6 4-6 4-6-4 6-4m12 0 6 4-6 4-6-4 6-4M6 21l6-4 6 4-6 3z"/>' : null;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 64 64"><rect x="2" y="2" width="60" height="60" rx="15" fill="${color}"/>${artwork ? `<g transform="translate(12 10) scale(1.65)">${artwork}</g>` : `<text x="32" y="42" fill="white" text-anchor="middle" font-family="Arial,sans-serif" font-weight="bold" font-size="${letters.length > 2 ? 22 : 29}">${letters}</text>`}</svg>`;
  const png = Buffer.from(await page.evaluate(async svg => {
   const img = new Image(); img.src = 'data:image/svg+xml;base64,' + btoa(unescape(encodeURIComponent(svg))); await img.decode();
   const canvas = document.createElement('canvas'); canvas.width = canvas.height = 64; canvas.getContext('2d').drawImage(img,0,0);
   return Array.from(new Uint8Array(await (await fetch(canvas.toDataURL())).arrayBuffer()));
  },svg));
  const header = Buffer.alloc(22); header.writeUInt16LE(1,2); header.writeUInt16LE(1,4); header[6] = header[7] = 64;
  header.writeUInt16LE(1,10); header.writeUInt16LE(32,12); header.writeUInt32LE(png.length,14); header.writeUInt32LE(22,18);
  const key = id.replaceAll(' ','-'); fs.writeFileSync(`src-tauri/icons/drives/${key}.ico`,Buffer.concat([header,png]));
  arms.push(`        "${id}" => ("${key}", include_bytes!("../icons/drives/${key}.ico")),`);
 }
 fs.writeFileSync('src-tauri/src/mount_icons.rs', '// Generated by scripts/create-drive-icons.cjs; no remote icon fetching.\npub(crate) fn icon(provider: &str) -> (&\'static str, &\'static [u8]) {\n    match provider {\n' + arms.join('\n') + '\n        _ => ("cloudloom", include_bytes!("../icons/icon.ico")),\n    }\n}\n');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
